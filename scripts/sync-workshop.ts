// Build the site's content/ folder from the workshop repository.
//
// The workshop repo is the single source of truth and is used exactly as it
// is. This script fetches it, splits its README.md into a few site pages by
// `##` sections, turns each Exercise*.md into a subpage of "Exercises",
// rewrites links so they work on the site, turns blockquotes into branded
// callouts, and writes the result to content/.
// content/ is generated: never edit it by hand, edit the workshop repo.
//
//   bun scripts/sync-workshop.ts                      # fetch WORKSHOP_REF (default main) into .workshop/
//   WORKSHOP_DIR=../Run-AI-agents-with-LUMI-Workshop bun scripts/sync-workshop.ts   # use a local checkout as-is

import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join, posix } from "node:path";
import GithubSlugger from "github-slugger";

const REPO = "lumi-ai-factory/Run-AI-agents-with-LUMI-Workshop";
const REF = process.env.WORKSHOP_REF || "main";
const ROOT = process.cwd();
const CONTENT = join(ROOT, "content");
const CACHE = join(ROOT, ".workshop");

/**
 * How README.md is split. A page starts at the `##` heading matching `starts`
 * (the first page starts at the top). Every other `##` section stays on the
 * page before it, so new sections in the README need no change here.
 */
const README_PAGES: { slug: string; title: string; starts: RegExp | null }[] = [
  { slug: "", title: "Home", starts: null },
  { slug: "setup", title: "Setup", starts: /^setup$/i },
  { slug: "exercises", title: "Exercises", starts: /exercises/i },
  { slug: "after-the-workshop", title: "After the workshop", starts: /^after the workshop/i },
];
const EXERCISES_PARENT = "Exercises";

// ---------------------------------------------------------------- fetch

function git(args: string[], cwd?: string) {
  execFileSync("git", args, { cwd, stdio: ["ignore", "ignore", "inherit"] });
}

function workshopDir(): string {
  if (process.env.WORKSHOP_DIR) return process.env.WORKSHOP_DIR;
  try {
    if (existsSync(join(CACHE, ".git"))) {
      git(["fetch", "--depth", "1", "origin", REF], CACHE);
      git(["reset", "--hard", "FETCH_HEAD"], CACHE);
    } else {
      rmSync(CACHE, { recursive: true, force: true });
      git(["clone", "--depth", "1", "--branch", REF, `https://github.com/${REPO}.git`, CACHE]);
    }
  } catch (e) {
    if (!existsSync(join(CACHE, "README.md"))) throw e;
    console.warn(`[sync-workshop] could not update ${REPO}, using the cached copy in .workshop/`);
  }
  return CACHE;
}

// ---------------------------------------------------------------- helpers

/** Split markdown into lines, marking which are inside fenced code blocks. */
function lines(md: string): { text: string; code: boolean }[] {
  let fence = "";
  return md.split("\n").map((text) => {
    const m = text.match(/^\s*(`{3,}|~{3,})/);
    if (m) {
      if (!fence) fence = m[1];
      else if (m[1][0] === fence[0] && m[1].length >= fence.length) fence = "";
      return { text, code: true };
    }
    return { text, code: !!fence };
  });
}

function frontmatter(fields: Record<string, string | number | undefined>, source: string) {
  const body = Object.entries(fields)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => `${k}: ${typeof v === "number" ? v : JSON.stringify(v)}`)
    .join("\n");
  return `---\n# Generated by scripts/sync-workshop.ts from ${REPO}/${source}. Edit it there.\n${body}\n---\n\n`;
}

// ---------------------------------------------------------------- build

const dir = workshopDir();
const read = (f: string) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n");

interface OutPage {
  slug: string;
  source: string;
  fields: Record<string, string | number | undefined>;
  body: string;
}
const readmeOut: OutPage[] = [];
const exerciseOut: OutPage[] = [];

// README.md -> several pages
const readmePages = README_PAGES.map((p) => ({
  ...p,
  lines: [] as string[],
  found: p.starts === null,
}));
let current = 0;
for (const { text, code } of lines(read("README.md"))) {
  const h2 = !code && text.match(/^##\s+(.+?)\s*#*\s*$/);
  if (h2) {
    const next = readmePages.findIndex((p, i) => i > current && p.starts?.test(h2[1]));
    if (next !== -1) {
      current = next;
      readmePages[next].found = true;
    }
  }
  readmePages[current].lines.push(text);
}
for (const p of readmePages.filter((p) => !p.found))
  console.warn(
    `[sync-workshop] README.md has no "##" heading matching ${p.starts} for page "${p.title}"`,
  );

// Which README page each heading ended up on, for rewriting "#anchor" links.
const anchorPage = new Map<string, string>();
const pageTopAnchor = new Map<string, string>();

readmePages.forEach((p, i) => {
  if (!p.found) return;
  let ls = p.lines;
  if (i > 0) {
    // The page's first "##" becomes its "#" title. If it was the only "##",
    // lift its subsections one level so they show up in the page contents.
    const h2count = lines(ls.join("\n")).filter((l) => !l.code && /^##\s/.test(l.text)).length;
    let first = true;
    ls = lines(ls.join("\n")).map(({ text, code }) => {
      if (code) return text;
      if (first && /^##\s/.test(text)) {
        first = false;
        return text.slice(1);
      }
      if (h2count === 1 && /^#{3,6}\s/.test(text)) return text.slice(1);
      return text;
    });
  }
  const slugger = new GithubSlugger();
  for (const l of lines(ls.join("\n"))) {
    const h = !l.code && l.text.match(/^#{1,6}\s+(.+?)\s*#*\s*$/);
    if (!h) continue;
    const id = slugger.slug(h[1]);
    if (!pageTopAnchor.has(p.slug)) pageTopAnchor.set(p.slug, id);
    if (!anchorPage.has(id)) anchorPage.set(id, p.slug);
  }
  readmeOut.push({
    slug: p.slug,
    source: "README.md",
    fields: { title: p.title, nav_order: readmeOut.length + 1 },
    body: ls.join("\n").trim() + "\n",
  });
});

// Exercise*.md -> subpages of Exercises
const exerciseSlug = new Map<string, string>();
const exerciseFiles = readdirSync(dir)
  .map((f) => ({ f, n: f.match(/^Exercise(\d+)\.md$/i)?.[1] }))
  .filter((x): x is { f: string; n: string } => !!x.n)
  .sort((a, b) => Number(a.n) - Number(b.n));

for (const { f, n } of exerciseFiles) {
  const out = lines(read(f));
  const h1 = out.findIndex((l) => !l.code && /^#\s/.test(l.text));
  const name = h1 === -1 ? f.replace(/\.md$/, "") : out[h1].text.replace(/^#\s+/, "").trim();
  const title = `Exercise ${n}: ${name}`;
  if (h1 === -1) out.unshift({ text: `# ${title}\n`, code: false });
  else out[h1].text = `# ${title}`;
  exerciseSlug.set(f.toLowerCase(), `exercise-${n}`);
  exerciseOut.push({
    slug: `exercise-${n}`,
    source: f,
    fields: { title, parent: EXERCISES_PARENT, nav_order: Number(n) + 1 },
    body:
      out
        .map((l) => l.text)
        .join("\n")
        .trim() + "\n",
  });
}

const pages = [...readmeOut, ...exerciseOut];

// ---------------------------------------------------------------- links

function route(slug: string, anchor?: string) {
  const path = slug === "" ? "/" : `/${slug}`;
  return anchor && pageTopAnchor.get(slug) !== anchor ? `${path}#${anchor}` : path;
}

function rewriteTarget(target: string, page: OutPage): string {
  if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("//")) return target;
  const [file, anchor] = target.split("#");

  if (!file) {
    // "#setup" on a README page may now live on another page.
    if (page.source !== "README.md") return target;
    const to = anchorPage.get(anchor);
    return to === undefined || to === page.slug ? target : route(to, anchor);
  }

  const rel = posix.normalize(posix.join(posix.dirname(page.source), file)).replace(/^\.\//, "");
  if (rel === "README.md") return route((anchor && anchorPage.get(anchor)) || "", anchor);
  const ex = exerciseSlug.get(rel.toLowerCase());
  if (ex) return route(ex, anchor);

  // Anything else (code, data, other READMEs) is shown on GitHub.
  const abs = join(dir, rel);
  const kind = existsSync(abs) && statSync(abs).isDirectory() ? "tree" : "blob";
  if (!existsSync(abs))
    console.warn(`[sync-workshop] ${page.source}: link to missing file "${file}"`);
  return `https://github.com/${REPO}/${kind}/${REF}/${rel}${anchor ? `#${anchor}` : ""}`;
}

for (const page of pages) {
  page.body = lines(page.body)
    .map(({ text, code }) =>
      code
        ? text
        : text
            .replace(/(\]\()(<[^>]+>|[^)\s]+)((?:\s+"[^"]*")?\))/g, (_, a, t, b) => {
              const bare = t.startsWith("<") ? t.slice(1, -1) : t;
              return `${a}${rewriteTarget(bare, page)}${b}`;
            })
            .replace(/(\bhref=")([^"]+)(")/g, (_, a, t, b) => `${a}${rewriteTarget(t, page)}${b}`),
    )
    .join("\n");
}

// ---------------------------------------------------------------- callouts

// Blockquotes -> the template's branded callouts.
//
// A blockquote that is not already a callout becomes one. If its first line is
// a short label ending in a colon ("> Before you start:"), or a bold label
// ("> **Before you start:** text"), that label becomes the callout's title.
// Its type is "warning" when the label sounds like one, otherwise "note".
//
// GitHub alerts ("> [!WARNING]") are kept; GitHub's IMPORTANT and CAUTION,
// which the template lacks, map to the closest type.
const ALERT_TYPE: Record<string, string> = { important: "info", caution: "warning" };
const WARNING_LABEL = /before you|warning|caution|important|careful|do not|don't|never/i;

const capitalise = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

for (const page of pages) {
  const ls = lines(page.body);
  for (let i = 0; i < ls.length; i++) {
    const quote = (j: number) => !!ls[j] && !ls[j].code && /^\s*>/.test(ls[j].text);
    // Only the first line of each blockquote.
    if (!quote(i) || quote(i - 1)) continue;
    const [, prefix, first] = ls[i].text.match(/^(\s*>\s?)(.*)$/)!;

    const alert = first.match(/^\[!(\w+)\](.*)$/);
    if (alert) {
      const type = alert[1].toLowerCase();
      ls[i].text = `${prefix}[!${ALERT_TYPE[type] ?? type}]${alert[2]}`;
      continue;
    }

    let title = "";
    const label = first.match(/^([^.!?]{1,40}):\s*$/); // "> Before you start:"
    const bold = first.match(/^\*\*(.+?):?\*\*:?\s*(.*)$/); // "> **Before you start:** text"
    if (label && quote(i + 1)) {
      title = label[1].trim();
      ls.splice(i, 1);
      ls[i].text = ls[i].text.replace(/^(\s*>\s?)(.*)$/, (_, p, rest) => p + capitalise(rest));
    } else if (bold) {
      title = bold[1].trim();
      if (bold[2]) ls[i].text = prefix + capitalise(bold[2]);
      else ls.splice(i, 1);
    }
    const type = WARNING_LABEL.test(title) ? "warning" : "note";
    ls.splice(i, 0, { text: `${prefix}[!${type}]${title ? ` ${title}` : ""}`, code: false });
    i++;
  }
  page.body = ls.map((l) => l.text).join("\n");
}

// ---------------------------------------------------------------- write

rmSync(CONTENT, { recursive: true, force: true });
mkdirSync(CONTENT, { recursive: true });
for (const page of pages) {
  writeFileSync(
    join(CONTENT, `${page.slug || "index"}.md`),
    frontmatter(page.fields, page.source) + page.body,
  );
}
console.log(
  `[sync-workshop] wrote ${pages.length} pages from ${REPO}${process.env.WORKSHOP_DIR ? ` (local: ${dir})` : `@${REF}`}`,
);
